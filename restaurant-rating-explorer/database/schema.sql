-- ============================================================================
-- SECTION 3: APPLICATION VIEWS
-- ============================================================================

-- ----------------------------------------------------------------------------
-- View: public.v_restaurant_summary
-- Aggregates ratings metrics and review counts for each restaurant.
-- Preserves NULL average ratings for unrated restaurants (Requirement 7).
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.v_restaurant_summary AS
SELECT 
    r.place_id,
    r.name,
    r.city,
    r.state,
    r.country,
    r.price,
    r.alcohol,
    r.smoking_area,
    r.dress_code,
    r.accessibility,
    r.latitude,
    r.longitude,
    COUNT(rt.user_id) AS total_reviews,
    ROUND(AVG(rt.rating)::NUMERIC, 2) AS avg_overall_rating,
    ROUND(AVG(rt.food_rating)::NUMERIC, 2) AS avg_food_rating,
    ROUND(AVG(rt.service_rating)::NUMERIC, 2) AS avg_service_rating
FROM public.restaurants r
LEFT JOIN public.ratings rt ON r.place_id = rt.place_id
GROUP BY 
    r.place_id, r.name, r.city, r.state, r.country, 
    r.price, r.alcohol, r.smoking_area, r.dress_code, 
    r.accessibility, r.latitude, r.longitude;

COMMENT ON VIEW public.v_restaurant_summary IS 'Consolidated summary of restaurants with computed average ratings and review counts. Unrated restaurants retain NULL averages to distinguish from score 0.';

-- ----------------------------------------------------------------------------
-- View: public.v_restaurant_cuisines
-- Matches active restaurants with their catalogued cuisine types.
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.v_restaurant_cuisines AS
SELECT 
    r.place_id,
    r.name AS restaurant_name,
    r.city,
    r.state,
    rc.cuisine
FROM public.restaurants r
JOIN public.restaurant_cuisines rc ON r.place_id = rc.place_id;

COMMENT ON VIEW public.v_restaurant_cuisines IS 'Convenience view linking active restaurants to their catalogued cuisines';

-- ----------------------------------------------------------------------------
-- View: public.v_unmatched_cuisines
-- Surfaces all 804 preserved cuisine records from ChefMoz that do not have
-- matching entries in geoplaces2 (Requirement 1 & 4 verification).
-- ----------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.v_unmatched_cuisines AS
SELECT 
    rc.place_id,
    rc.cuisine
FROM public.restaurant_cuisines rc
LEFT JOIN public.restaurants r ON rc.place_id = r.place_id
WHERE r.place_id IS NULL;

COMMENT ON VIEW public.v_unmatched_cuisines IS 'Shows preserved ChefMoz cuisine entries without geoplaces2 records (Requirement 1 & 4 verification: exactly 804 rows)';


-- ============================================================================
-- SECTION 4: ISOLATED CONSUMER ANALYTICS SCHEMA (Requirement 5)
-- The public restaurant explorer application operates exclusively within
-- the 'public' schema. Consumer demographic profiles, personal payment
-- preferences, and personal cuisine tastes are isolated in 'consumer_analytics'
-- to safeguard user privacy and prevent exposure to the public-facing application.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS consumer_analytics;

-- ----------------------------------------------------------------------------
-- Table: consumer_analytics.consumer_profiles
-- Sourced from: data/raw/userprofile.csv (138 records)
-- Private consumer demographic, psychographic, and lifestyle data.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS consumer_analytics.consumer_profiles (
    user_id             VARCHAR(10) NOT NULL,
    latitude            NUMERIC(10, 7),
    longitude           NUMERIC(10, 7),
    smoker              VARCHAR(10),
    drink_level         VARCHAR(30),
    dress_preference    VARCHAR(30),
    ambience            VARCHAR(30),
    transport           VARCHAR(30),
    marital_status      VARCHAR(20),
    hijos               VARCHAR(20),
    birth_year          INTEGER,
    interest            VARCHAR(30),
    personality         VARCHAR(30),
    religion            VARCHAR(30),
    activity            VARCHAR(30),
    color               VARCHAR(20),
    weight              NUMERIC(5, 2),
    budget              VARCHAR(20),
    height              NUMERIC(4, 2),
    created_at          TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_consumer_profiles PRIMARY KEY (user_id)
);

COMMENT ON SCHEMA consumer_analytics IS 'Private schema isolated from public application to protect user demographics and preferences (Requirement 5)';
COMMENT ON TABLE consumer_analytics.consumer_profiles IS 'Personal consumer profiles and demographic attributes, sourced from userprofile.csv';

-- ----------------------------------------------------------------------------
-- Table: consumer_analytics.consumer_payment_preferences
-- Sourced from: data/raw/userpayment.csv (177 records)
-- Personal payment methods preferred by consumers.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS consumer_analytics.consumer_payment_preferences (
    user_id         VARCHAR(10) NOT NULL,
    payment_method  VARCHAR(50) NOT NULL,

    CONSTRAINT pk_consumer_payment_preferences PRIMARY KEY (user_id, payment_method),
    CONSTRAINT fk_consumer_payments_user FOREIGN KEY (user_id)
        REFERENCES consumer_analytics.consumer_profiles (user_id) ON DELETE CASCADE
);

COMMENT ON TABLE consumer_analytics.consumer_payment_preferences IS 'Consumer payment method preferences, sourced from userpayment.csv';

-- ----------------------------------------------------------------------------
-- Table: consumer_analytics.consumer_cuisine_preferences
-- Sourced from: data/raw/usercuisine.csv (330 records)
-- Cuisines preferred by individual consumers.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS consumer_analytics.consumer_cuisine_preferences (
    user_id         VARCHAR(10) NOT NULL,
    cuisine         VARCHAR(50) NOT NULL,

    CONSTRAINT pk_consumer_cuisine_preferences PRIMARY KEY (user_id, cuisine),
    CONSTRAINT fk_consumer_cuisines_user FOREIGN KEY (user_id)
        REFERENCES consumer_analytics.consumer_profiles (user_id) ON DELETE CASCADE
);

COMMENT ON TABLE consumer_analytics.consumer_cuisine_preferences IS 'Consumer cuisine preferences, sourced from usercuisine.csv';

-- Consumer Indexes
CREATE INDEX IF NOT EXISTS idx_consumer_profiles_budget ON consumer_analytics.consumer_profiles (budget);
CREATE INDEX IF NOT EXISTS idx_consumer_profiles_activity ON consumer_analytics.consumer_profiles (activity);
CREATE INDEX IF NOT EXISTS idx_consumer_payments_user_id ON consumer_analytics.consumer_payment_preferences (user_id);
CREATE INDEX IF NOT EXISTS idx_consumer_cuisines_user_id ON consumer_analytics.consumer_cuisine_preferences (user_id);
