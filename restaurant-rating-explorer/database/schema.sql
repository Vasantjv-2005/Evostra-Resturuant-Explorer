-- ============================================================================
-- PostgreSQL Database Schema: restaurant_explorer
-- Dataset: Restaurant & Consumer Data (CENIDET / Recommender Systems Domain)
-- Target Database: restaurant_explorer
-- Script: database/schema.sql
-- ============================================================================
-- Architectural & Design Highlights:
--
-- 1. Separation of Concerns (Requirement 5):
--    - 'public' schema: Houses all public-facing application tables for the
--      Restaurant Explorer (restaurants, cuisines, payments, operating hours,
--      parking, and ratings).
--    - 'consumer_analytics' schema: Houses private consumer demographics,
--      payment preferences, and personal cuisine tastes. This guarantees that
--      sensitive consumer profiles are kept out of the public web application.
--
-- 2. Preservation of Unmatched Records (Requirement 1 & 4):
--    - 'chefmozcuisine.csv' contains 916 records across 769 distinct placeIDs.
--    - 'geoplaces2.csv' contains 130 surveyed restaurants.
--    - Only 95 placeIDs overlap (112 cuisine records).
--    - 674 placeIDs (804 rows) belong to the wider ChefMoz crawler dataset and
--      have no corresponding record in geoplaces2.csv.
--    - In accordance with Requirement 1 ("Preserve all 916 rows in chefmozcuisine.csv,
--      including the 804 unmatched cuisine rows; do not create fake restaurants
--      or discard records"), NO foreign key constraint referencing 'restaurants(place_id)'
--      is enforced on 'restaurant_cuisines'.
--    - Similarly, accepted payments, operating hours, and parking omit foreign keys
--      to restaurants because they also contain ChefMoz crawler places.
--
-- 3. Operating Hours Duplicate Handling (Requirement 2):
--    - 'chefmozhours4.csv' contains 2,339 rows with 271 duplicate rows.
--    - A surrogate primary key ('id INTEGER GENERATED BY DEFAULT AS IDENTITY')
--      ensures unique row identification without primary key collisions upon import.
--    - During CSV import, map destination columns (place_id, hours, days) so that
--      PostgreSQL generates identity IDs automatically.
--
-- 4. Unrated Restaurants & NULL Rating Preservation (Requirement 7):
--    - 'v_restaurant_summary' uses LEFT JOIN and preserves NULL for restaurants
--      without ratings (COUNT = 0), allowing the frontend to distinguish unrated
--      restaurants from those with a score of 0.
--
-- 5. Foreign Key Constraints:
--    - 'ratings.place_id' strictly references 'restaurants.place_id' (100% of
--      the 130 rated places in rating_final.csv exist in geoplaces2.csv).
-- ============================================================================

-- Ensure the public schema exists
CREATE SCHEMA IF NOT EXISTS public;

-- ============================================================================
-- SECTION 1: PUBLIC RESTAURANT APPLICATION TABLES
-- ============================================================================

-- ----------------------------------------------------------------------------
-- Table: public.restaurants
-- Sourced from: data/raw/geoplaces2.csv (130 records)
-- Core entity table containing restaurant profiles, locations, and attributes.
-- Note: 'created_at' defaults to CURRENT_TIMESTAMP; CSV import must explicitly
-- specify destination columns 1-21.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.restaurants (
    place_id        INTEGER NOT NULL,
    latitude        NUMERIC(10, 7) NOT NULL,
    longitude       NUMERIC(10, 7) NOT NULL,
    the_geom_meter  VARCHAR(64) NOT NULL,
    name            VARCHAR(100) NOT NULL,
    address         VARCHAR(255),
    city            VARCHAR(50),
    state           VARCHAR(50),
    country         VARCHAR(50),
    fax             VARCHAR(20),
    zip             VARCHAR(10),
    alcohol         VARCHAR(30),
    smoking_area    VARCHAR(30),
    dress_code      VARCHAR(30),
    accessibility   VARCHAR(30),
    price           VARCHAR(20),
    url             VARCHAR(255),
    rambience       VARCHAR(30),
    franchise       VARCHAR(5),
    area            VARCHAR(20),
    other_services  VARCHAR(30),
    created_at      TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_restaurants PRIMARY KEY (place_id),
    CONSTRAINT chk_restaurants_lat CHECK (latitude BETWEEN -90.0 AND 90.0),
    CONSTRAINT chk_restaurants_lon CHECK (longitude BETWEEN -180.0 AND 180.0),
    CONSTRAINT chk_restaurants_franchise CHECK (franchise IS NULL OR franchise IN ('t', 'f', 'true', 'false'))
);

COMMENT ON TABLE public.restaurants IS 'Primary restaurant information sourced from geoplaces2.csv';
COMMENT ON COLUMN public.restaurants.place_id IS 'Unique identifier for each restaurant (Primary Key)';
COMMENT ON COLUMN public.restaurants.the_geom_meter IS 'Geospatial hex point geometry';
COMMENT ON COLUMN public.restaurants.rambience IS 'Restaurant ambience (familiar, quiet)';
COMMENT ON COLUMN public.restaurants.franchise IS 'Franchise status (t: true, f: false)';

-- ----------------------------------------------------------------------------
-- Table: public.restaurant_cuisines
-- Sourced from: data/raw/chefmozcuisine.csv (916 records, 769 unique places)
-- Requirement 1: Preserves all 916 records (112 matched + 804 unmatched).
-- No foreign key constraint to restaurants table to avoid dropping unmatched
-- crawler data or inventing fake restaurants.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.restaurant_cuisines (
    place_id        INTEGER NOT NULL,
    cuisine         VARCHAR(50) NOT NULL,

    CONSTRAINT pk_restaurant_cuisines PRIMARY KEY (place_id, cuisine)
);

COMMENT ON TABLE public.restaurant_cuisines IS 'Cuisine types offered by restaurants, sourced from chefmozcuisine.csv. Retains all 916 records, including 804 unmatched ChefMoz places.';
COMMENT ON COLUMN public.restaurant_cuisines.place_id IS 'Restaurant ID. Intentionally unconstrained by FK to restaurants table to preserve unmatched ChefMoz records.';
COMMENT ON COLUMN public.restaurant_cuisines.cuisine IS 'Cuisine classification (e.g. Mexican, Italian, Seafood)';

-- ----------------------------------------------------------------------------
-- Table: public.restaurant_payments
-- Sourced from: data/raw/chefmozaccepts.csv (1,314 records, 615 unique places)
-- Accepted payment methods (cash, VISA, MasterCard-Eurocard, etc.)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.restaurant_payments (
    place_id        INTEGER NOT NULL,
    payment_method  VARCHAR(50) NOT NULL,

    CONSTRAINT pk_restaurant_payments PRIMARY KEY (place_id, payment_method)
);

COMMENT ON TABLE public.restaurant_payments IS 'Accepted payment methods per restaurant, sourced from chefmozaccepts.csv';
COMMENT ON COLUMN public.restaurant_payments.payment_method IS 'Payment method (e.g., cash, VISA, MasterCard-Eurocard)';

-- ----------------------------------------------------------------------------
-- Table: public.restaurant_operating_hours
-- Sourced from: data/raw/chefmozhours4.csv (2,339 records, 694 unique places)
-- Operating hours and active days of the week.
-- Uses surrogate PK (id) generated by default as identity because raw CSV
-- contains 271 duplicate rows.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.restaurant_operating_hours (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    place_id        INTEGER NOT NULL,
    hours           VARCHAR(100) NOT NULL,
    days            VARCHAR(50) NOT NULL,

    CONSTRAINT pk_restaurant_operating_hours PRIMARY KEY (id)
);

COMMENT ON TABLE public.restaurant_operating_hours IS 'Weekly operating schedules, sourced from chefmozhours4.csv. Surrogate ID handles raw duplicate entries.';
COMMENT ON COLUMN public.restaurant_operating_hours.id IS 'Surrogate primary key generated automatically by PostgreSQL';
COMMENT ON COLUMN public.restaurant_operating_hours.hours IS 'Operating time window (e.g., 08:00-21:00;)';
COMMENT ON COLUMN public.restaurant_operating_hours.days IS 'Days of applicability (e.g., Mon;Tue;Wed;Thu;Fri;)';

-- ----------------------------------------------------------------------------
-- Table: public.restaurant_parking
-- Sourced from: data/raw/chefmozparking.csv (702 records, 675 unique places)
-- Parking availability and parking lot types.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.restaurant_parking (
    place_id        INTEGER NOT NULL,
    parking_type    VARCHAR(50) NOT NULL,

    CONSTRAINT pk_restaurant_parking PRIMARY KEY (place_id, parking_type)
);

COMMENT ON TABLE public.restaurant_parking IS 'Parking facilities per restaurant, sourced from chefmozparking.csv';
COMMENT ON COLUMN public.restaurant_parking.parking_type IS 'Parking type (public, none, yes, valet parking, fee, street, validated parking)';

-- ----------------------------------------------------------------------------
-- Table: public.ratings
-- Sourced from: data/raw/rating_final.csv (1,161 records, 130 unique places)
-- User rating submissions on scale 0-2 (overall, food, service).
-- place_id strictly references public.restaurants(place_id).
-- user_id is maintained as an opaque reviewer handle, keeping consumer profile
-- data out of the public application.
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ratings (
    user_id         VARCHAR(10) NOT NULL,
    place_id        INTEGER NOT NULL,
    rating          SMALLINT NOT NULL,
    food_rating     SMALLINT NOT NULL,
    service_rating  SMALLINT NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_ratings PRIMARY KEY (user_id, place_id),
    CONSTRAINT fk_ratings_restaurant FOREIGN KEY (place_id)
        REFERENCES public.restaurants (place_id) ON DELETE CASCADE,
    CONSTRAINT chk_ratings_overall CHECK (rating BETWEEN 0 AND 2),
    CONSTRAINT chk_ratings_food CHECK (food_rating BETWEEN 0 AND 2),
    CONSTRAINT chk_ratings_service CHECK (service_rating BETWEEN 0 AND 2)
);

COMMENT ON TABLE public.ratings IS 'Consumer ratings and reviews for restaurants, sourced from rating_final.csv';
COMMENT ON COLUMN public.ratings.user_id IS 'Anonymized consumer reviewer handle (e.g. U1077)';
COMMENT ON COLUMN public.ratings.rating IS 'Overall restaurant rating: 0 (Low), 1 (Medium), 2 (High)';
COMMENT ON COLUMN public.ratings.food_rating IS 'Food quality rating: 0 (Low), 1 (Medium), 2 (High)';
COMMENT ON COLUMN public.ratings.service_rating IS 'Service quality rating: 0 (Low), 1 (Medium), 2 (High)';


